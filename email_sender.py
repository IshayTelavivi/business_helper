import os
import logging
import resend

logger = logging.getLogger(__name__)


def _build_html(client_name: str, results: list[dict], run_date: str, rtl: bool = True) -> str:
    direction = "rtl" if rtl else "ltr"
    align = "right" if rtl else "left"

    def score_color(score):
        if score >= 4:
            return "#22c55e"
        if score >= 3:
            return "#eab308"
        return "#f97316"

    rows = ""
    for r in results:
        contacts_html = ""
        for c in r.get("contacts", []):
            name = c.get("name", "Unknown")
            role = c.get("role", "")
            linkedin = c.get("linkedin_url", "")
            if linkedin:
                contacts_html += f'<p style="margin:4px 0;"><strong>{name}</strong> — {role} | <a href="{linkedin}" style="color:#2563eb;">LinkedIn</a></p>'
            else:
                contacts_html += f'<p style="margin:4px 0;"><strong>{name}</strong> — {role}</p>'

        score = r.get("score", 0)
        source_url = r.get("source_url", "")
        source_title = r.get("source_title", "Source")

        rows += f"""
        <div style="background:#ffffff; border:1px solid #e5e7eb; border-radius:8px; padding:20px; margin-bottom:16px;">
            <div style="display:flex; justify-content:space-between; align-items:center; margin-bottom:12px;">
                <h2 style="margin:0; color:#1f2937; font-size:18px;">{r.get('org_name', '')}</h2>
                <span style="background:{score_color(score)}; color:white; padding:4px 10px; border-radius:12px; font-size:14px; font-weight:bold;">{score}/5</span>
            </div>
            <p style="color:#6b7280; font-size:13px; margin:4px 0;"><strong>Signal:</strong> {r.get('signal', '')} | <strong>Sector:</strong> {r.get('sector', '')}</p>
            <p style="color:#374151; margin:12px 0;">{r.get('opportunity', '')}</p>
            <div style="background:#f9fafb; padding:12px; border-radius:6px; margin:12px 0;">
                <p style="margin:0 0 8px 0; font-weight:bold; color:#374151;">Contacts:</p>
                {contacts_html if contacts_html else '<p style="color:#9ca3af; margin:0;">No contacts found</p>'}
            </div>
            <div style="background:#eff6ff; padding:12px; border-radius:6px; margin:12px 0;">
                <p style="margin:0 0 8px 0; font-weight:bold; color:#1e40af;">Outreach Draft:</p>
                <p style="color:#374151; margin:0; white-space:pre-wrap;">{r.get('outreach_draft', '')}</p>
            </div>
            {f'<p style="margin:8px 0 0 0;"><a href="{source_url}" style="color:#2563eb; font-size:13px;">{source_title}</a></p>' if source_url else ''}
        </div>
        """

    return f"""
    <div style="direction:{direction}; text-align:{align}; font-family:Arial, Helvetica, sans-serif; max-width:700px; margin:0 auto; background:#f3f4f6; padding:24px;">
        <div style="background:#1f2937; color:white; padding:20px; border-radius:8px 8px 0 0; text-align:center;">
            <h1 style="margin:0; font-size:22px;">Lead Generation Results</h1>
            <p style="margin:8px 0 0 0; color:#9ca3af; font-size:14px;">{client_name} — {run_date}</p>
        </div>
        <div style="padding:16px 0;">
            {rows}
        </div>
        <div style="text-align:center; padding:16px; color:#9ca3af; font-size:12px;">
            <p>Generated by Business Helper</p>
        </div>
    </div>
    """


def send_results_email(
    recipient: str,
    client_name: str,
    results: list[dict],
    run_date: str,
    rtl: bool = True,
) -> dict:
    api_key = os.getenv("RESEND_API_KEY")
    if not api_key:
        raise ValueError("RESEND_API_KEY not set")

    resend.api_key = api_key

    html = _build_html(client_name, results, run_date, rtl)
    sender = os.getenv("DEFAULT_SENDER_EMAIL", "onboarding@resend.dev")

    params = {
        "from": sender,
        "to": [recipient],
        "subject": f"Lead Generation Results — {client_name} — {run_date}",
        "html": html,
    }

    try:
        response = resend.Emails.send(params)
        logger.info("Email sent to %s: %s", recipient, response)
        return response
    except Exception as e:
        logger.error("Failed to send email: %s", e)
        raise
